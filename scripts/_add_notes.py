def entry(key, note):
    j = lambda s: json.dumps(s, ensure_ascii=False)
    theses_lines = ',\n'.join('      ' + j(t) for t in note['theses'])
    return (
        '  ' + j(key) + ': {\n'
        '    "theses": [\n' + theses_lines + '\n    ],\n'
        '    "takeaway": ' + j(note['takeaway']) + '\n'
        '  }'
    )

path = 'js/notes-data.js'
with open(path, encoding='utf-8') as f:
    text = f.read()

idx = text.rfind('\n};')
if idx == -1:
    raise SystemExit('Could not find closing "\\n};"')
head = text[:idx]           # ends with '\n  }' (last note close)
# tail = text[idx:]          # '\n};'

blocks = ',\n'.join(entry(k, v) for k, v in NOTES.items())
new_text = head + ',\n' + blocks + '\n};'

with open(path, 'w', encoding='utf-8') as f:
    f.write(new_text)

